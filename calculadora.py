print(f"Insira dois valores numericos para utilizar a caluladora: ")

valor1 = float(input("\nDigite o primeiro valor: "))
valor2 = float(input("\nDigite o segundo valor: "))

print("\nSoma: ", valor1 + valor2)
print("Diferença: ", valor1 - valor2)
print("Produto: ", valor1 * valor2)
print("Quociente: ", valor1 / valor2)
print("Potencia: ", valor1 ** valor2)
print("Resto da divisão: ", valor1 % valor2)
print("Divisão inteira: ", valor1 // valor2)